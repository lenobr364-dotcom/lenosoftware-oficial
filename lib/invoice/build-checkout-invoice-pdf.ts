import { jsPDF } from "jspdf";

export type InvoicePdfInput = {
  invoiceNumber: string;
  issuedAtIso: string;
  planLabel: string;
  amountFormatted: string;
  currencyCode: string;
  stripeSessionId: string;
};

/** PDF simples (recibo) — Leno.Software & Lumen Onel / ChemVault Global. */
export function buildCheckoutInvoicePdf(input: InvoicePdfInput): Uint8Array {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const w = doc.internal.pageSize.getWidth();
  let y = 48;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("ChemVault Global", 48, y);
  y += 28;
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text("Commercial receipt / invoice (indicative)", 48, y);
  y += 36;

  doc.setFont("helvetica", "bold");
  doc.text("Seller (50 / 50 venture)", 48, y);
  y += 18;
  doc.setFont("helvetica", "normal");
  doc.text("Leno César & Lumen Onel — leno.software", 48, y);
  y += 14;
  doc.text("BIJU Global Technology · ChemVault licensing infrastructure", 48, y);
  y += 32;

  doc.setFont("helvetica", "bold");
  doc.text("Invoice details", 48, y);
  y += 20;
  doc.setFont("helvetica", "normal");
  doc.text(`Invoice no.: ${input.invoiceNumber}`, 48, y);
  y += 16;
  doc.text(`Date (UTC): ${input.issuedAtIso}`, 48, y);
  y += 16;
  doc.text(`Plan: ${input.planLabel}`, 48, y);
  y += 16;
  doc.text(`Amount: ${input.amountFormatted} (${input.currencyCode})`, 48, y);
  y += 16;
  doc.text(`Stripe session: ${input.stripeSessionId}`, 48, y);
  y += 40;

  doc.setFontSize(9);
  doc.setTextColor(90, 90, 90);
  const foot =
    "This document is an indicative receipt generated by ChemVault after checkout. Executed license terms, tax IDs, and statutory invoices may be issued separately per contract.";
  const lines = doc.splitTextToSize(foot, w - 96);
  doc.text(lines, 48, y);

  doc.setTextColor(0, 0, 0);
  const out = doc.output("arraybuffer");
  return new Uint8Array(out);
}
